/** لعبة جاهزة كاملة (المحتوى بيتولّد كل مرة عشان الترتيب يتغيّر) */
export function packGame(id) {
    const p = PACKS.find((x) => x.id === id);
    return p ? { title: p.title, template: p.template, subject: p.subject, content: p.build(), pack: p.id } : null;
}
